def search_symbols(query: str, limit: int = 20) -> list[str]:
    q = query.upper()
    exact = [s for s in ALL_STOCKS if s == q]
    prefix = [s for s in ALL_STOCKS if s.startswith(q) and s != q]
    contains = [s for s in ALL_STOCKS if q in s and s != q and not s.startswith(q)]
    return (exact + prefix + contains)[:limit]
