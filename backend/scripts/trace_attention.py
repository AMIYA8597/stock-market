import os
import sys
import asyncio
import logging

sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
logging.basicConfig(level=logging.WARNING, format="%(message)s")

from app.services.prediction_engine import get_full_prediction
from app.services.intelligence_service import IntelligenceService

async def trace_attention():
    print("--- TRACING ATTENTION EXTRACTOR ---")
    symbol = "RELIANCE.NS"
    print(f"Fetching full prediction for {symbol} (bypassing cache)...")

    # We pass bypass_cache=True to ensure it runs the real model inference
    pred = await get_full_prediction(symbol, bypass_cache=True)
    ensemble = pred.get("ensemble", {})
    lstm_data = ensemble.get("lstm_attn", {})
    if lstm_data.get("status") != "trained":
        print("LSTM-Attention model not trained or available. Please train it first.")
        return

    attn_peaks = lstm_data.get("attention_peaks", [])
    print(f"Number of attention peaks generated by prediction engine: {len(attn_peaks)}")
    if len(attn_peaks) > 0:
        print("Top 3 attention peaks directly from the model:")
        for peak in sorted(attn_peaks, key=lambda x: x["weight"], reverse=True)[:3]:
            print(f"  Date: {peak['date']}, Weight: {peak['weight']:.4f}")

    print("\nCalling the Explainability API to verify integration...")
    service = IntelligenceService()
    res = service.get_attention(symbol, "lstm_attn")

    print(f"API Model: {res.model}")
    print("API Top Timesteps extracted:")
    for peak in res.top_timesteps[:3]:
        print(f"  Date: {peak['date']}, Weight: {peak['weight']:.4f}")

    if len(res.top_timesteps) > 0 and len(attn_peaks) > 0:
        # Check if they match
        api_top_weight = float(res.top_timesteps[0]["weight"])
        pred_top_weight = float(sorted(attn_peaks, key=lambda x: x["weight"], reverse=True)[0]["weight"])
        if abs(api_top_weight - pred_top_weight) < 1e-4:
            print("ATTENTION MATCH VERIFIED! API is serving the exact model attention weights.")
        else:
            print("Mismatch! API weights don't match the model weights.")

asyncio.run(trace_attention())
